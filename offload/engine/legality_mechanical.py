"""The mechanical legality evidence of a finding, with no AI reading: the rules engine's verdict and
reasons (offload.engine.prerun.rules_witness), the result hazards (prerun.result_hazards), a second
witness of another compiler family and the source of the expected value, from the finding's cells in
the committed rows (offload.engine.site.matrix). offload.engine.legality_review.verdict reads it.

The second witness: a toolchain of a family that does not fail the program, other than GCC (never
evidence of legality), built and ran it correctly; or AMD's front end accepted it (a stored row) when AFAR is not a
failing family. The expected value of a wrong answer: a run
of another family, GCC included (a value, not a legality claim), printed it ("other-family"); else the
program checks its own result ("self-check": a RESULT line with check=).

The front end's verdicts are stored (catalog/finding_witness.yaml, written on a compute node by
`tools/review/review.py mechanical --frontend`); ``evidence`` reads them and runs nothing."""
from __future__ import annotations

import datetime
import re
import subprocess
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
WITNESS = ROOT / "catalog" / "finding_witness.yaml"
HEAD = "# Generated by `tools/review/review.py mechanical --frontend`: front ends of compilers of\n" \
       "# another family on findings no run of another family witnesses. Do not edit.\n"
NOT_A_WITNESS = {"gcc"}         # a family that is never evidence that a program is legal


def _family(tc: str) -> str:
    from offload.engine.site import matrix as M
    return M.VERSIONS[tc][0]


def load_rows(path: Path = WITNESS) -> list[dict]:
    return list((yaml.safe_load(path.read_text()) or {}).get("witnesses") or []) if path.is_file() else []


def write_rows(rows: list[dict], path: Path = WITNESS) -> None:
    rows = sorted(rows, key=lambda r: (r["finding"], r["checker"]))
    path.write_text(HEAD + yaml.safe_dump({"witnesses": rows}, sort_keys=False, width=1000))


# the front end of a family per language: compilers that share one are not independent of each other
LINEAGE = {"c": {"afar": "clang", "cce": "clang", "intel": "clang"},
           "f90": {"afar": "flang", "cce": "cray-fortran", "intel": "intel-fortran"}}
# the outcomes a front end decides: a correct run of a failing compiler's front end does not witness them
REFUSALS = ("rejected", "compile_reject", "ice")


def lineage(family: str, lang: str) -> str:
    return LINEAGE["c" if lang == "c" else "f90"].get(family, family)


def result_of(r: dict, lang: str) -> str:
    """A stored row's result: a refusal whose message is a crash of the checker (offload.engine.harness
    patterns, ice) is "ice", one that says the feature is not implemented or not supported
    (not_implemented) "unsupported"; neither is a verdict on the program."""
    if r["result"] != "reject" or not r.get("message"):
        return r["result"]
    from offload.engine.harness import classify_message
    found = classify_message(r["family"], r["message"].replace(" | ", "\n"), ("ice", "not_implemented"), lang)
    return {"ice": "ice", "not_implemented": "unsupported"}[found[0]] if found else "reject"


def stored(rows: list, fid: str, sha: str, failing: set, lang: str = "f90") -> str | None:
    """accept | reject of a stored front end on the current source, of a family that does not fail
    and a lineage no failing compiler shares; "ignored" and "unsupported" are neither."""
    bad = {lineage(f, lang) for f in failing}
    got = [result_of(r, lang) for r in rows if r["finding"] == fid and r["sha256"] == sha
           and r["family"] not in failing and lineage(r["family"], lang) not in bad]
    got = [g for g in got if g in ("accept", "reject")]
    return "accept" if "accept" in got else ("reject" if got else None)


def needs_frontend(findings: dict, rows: list, witnessed: set, family: str = "afar") -> list[str]:
    """The findings ({id: (sha, failing families)}) with no witness from a run and no stored row of
    the checker family on their current source, whose failing families leave it as a witness."""
    return sorted(f for f, (sha, failing) in findings.items()
                  if f not in witnessed and family not in failing
                  and not any(r["finding"] == f and r["sha256"] == sha and r.get("family", "afar") == family
                              for r in rows))


def checker_rows(fid: str, sha: str, text: str, lang: str, model: str, family: str = "nvhpc") -> list[dict] | None:
    """The front ends of a checker family (catalog/machines.yaml independent_checkers: NVHPC over ssh,
    Intel on a compute node) on a finding: its rows, or None when a checker cannot run or be reached.
    "ignored" (directives dropped with a warning) is no accept."""
    from offload.engine.confirm import witness as W
    out = []
    for name in [n for n in W.names_for(lang, model) if W.checkers()[n].get("family") == family]:
        try:
            r = W.check(fid, text, lang, sha, model, name)
        except (RuntimeError, OSError, ValueError, subprocess.TimeoutExpired):
            return None
        out.append({"finding": fid, "sha256": sha, "checker": name, "family": family, "version": r["version"],
                    "result": r["result"], "message": r["message"], "date": r["date"]})
    return out


def nvhpc_rows(fid: str, sha: str, text: str, lang: str, model: str) -> list[dict] | None:
    return checker_rows(fid, sha, text, lang, model, "nvhpc")


def frontend_row(fid: str, sha: str, text: str, lang: str, model: str) -> dict | None:
    """Run AMD's front end (a compute node) on a finding: its stored row, or None if it cannot run."""
    from offload.engine import prerun
    ok, why = prerun.frontend_witness((text, lang, model))
    if ok is None:
        return None
    return {"finding": fid, "sha256": sha, "checker": "afar-frontend", "family": "afar",
            "result": "accept" if ok else "reject", "message": "; ".join(why)[:300],
            "date": datetime.date.today().isoformat()}


_V60 = re.compile(r"version 60\b|-fopenmp-version=60\b|OpenMP 6\.0", re.I)


def spec_version(text: str) -> int:
    """60 when the program's header names OpenMP 6.0 (its catalog version, -fopenmp-version=60 or the
    generator's line), else 52."""
    return 60 if _V60.search(text) else 52


def _rules(text: str, lang: str, model: str):
    """The rules engine at OpenMP 5.2, and at 6.0 when 5.2 cannot read a program the header says is 6.0."""
    from offload.engine import prerun
    ok, why = prerun.rules_witness((text, lang, model))
    if ok is None and model == "omp" and spec_version(text) == 60:
        ok, why = prerun.rules_witness((text, lang, model, 60))
    return ok, why


def evidence(text: str, lang: str, model: str, outcome: str, cells: list, rows: list = (),
             fid: str = "", sha: str = "") -> dict:
    from offload.engine import prerun
    ok, why = _rules(text, lang, model)
    rules = "accept" if ok else ("reject" if ok is False else "unreadable")
    hazards = prerun.result_hazards((text, lang, model))
    if not hazards and model == "omp" and spec_version(text) == 60:
        hazards = prerun.result_hazards((text, lang, model, 60))
    failing = {_family(c.tc) for c in cells if c.state == "fails-like"}
    others = [c for c in cells if c.state == "correct" and _family(c.tc) not in failing]
    bad = {lineage(f, lang) for f in failing} if outcome in REFUSALS else set()
    counted = [c for c in others if _family(c.tc) not in NOT_A_WITNESS and lineage(_family(c.tc), lang) not in bad]
    witness = "accept" if counted else "same-family"
    if witness != "accept":
        witness = stored(rows, fid, sha, failing, lang) or witness
    if others:
        expected = "other-family"
    elif re.search(r"RESULT[^\n]*check=", text):
        expected = "self-check"
    else:
        expected = "none"
    return {"rules": rules, "rules_why": list(why)[:6], "hazards": hazards, "witness": witness,
            "expected": expected, "outcome": outcome, "failing": sorted(failing),
            "witnesses": sorted({c.tc for c in counted}), "expected_from": sorted({c.tc for c in others}),
            "front_ends": {r["checker"]: result_of(r, lang) for r in rows if r["finding"] == fid and r["sha256"] == sha}}


# the code a verdict depends on: a change to any of it makes every record stale
CODE = ("offload/engine/prerun.py", "offload/engine/rules.py", "offload/engine/grammar.py",
        "offload/engine/legality_mechanical.py", "offload/engine/harness.py", "offload/engine/legality_review.py", "tools/review/review.py")


def code_hash() -> str:
    import hashlib
    h = hashlib.sha256()
    for f in CODE:
        h.update((ROOT / f).read_bytes())
    return h.hexdigest()


def inputs_hash(sha: str, outcome: str, cells: list, rows: list, fid: str, code: str) -> str:
    """The hash of what a finding's verdict is computed from: its program, outcome, cells, stored
    front-end rows and the code (``code_hash``)."""
    import hashlib
    import json
    mine = sorted((r["checker"], r["sha256"], r["result"]) for r in rows if r["finding"] == fid)
    states = sorted((c.tc, c.target, c.state) for c in cells)
    return hashlib.sha256(json.dumps([sha, outcome, states, mine, code]).encode()).hexdigest()
