! # Observation (kernel-body campaign; not a finding): AFAR on MI300A (HSA_XNACK=1): an array constructor assigned to
! # a component of an element of a derived-type array inside a target teams distribute parallel do writes records
! # that hold other iterations' values
!
! - status: an observation under the C finding data/findings/malloc/afar-device-malloc-in-kernel-corrupts-records.c, not a
!   finding. By the kernel-body generator's own legality model this program is `unspecified` (offload/engine/kbody_gen.py,
!   `validate(student_cfg())`; tests/engine/test_kbody_gen.py): it carries the student's `has_device_addr(gps)` with no `requires
!   unified_address`, and the clause is defined only where the device addresses host memory (5.2 §5.4.9 p.123 l.3-6); and only
!   AFAR's front end, the compiler under test, accepted it (no Fortran front end of another family was run on it, and the
!   rules witness does not model `has_device_addr`). docs/tooling/contributing.md: the failures of an unspecified program are
!   observations, never findings. Dropping `has_device_addr` would make it `defined`, but its rows and a front end of another
!   family (CCE ftn, NVHPC) would have to follow; they were not run
! - toolchains and modes that fail: afar (AFAR 24.3.0); mode: unified; -O2
! - build: amdflang -fopenmp --offload-arch=gfx942 -O2
! - failure: wrong_answer (check=fail); observed: `spheres 44032  ghost cells 11316224`; expected: compiles and runs to
!   completion, printing `RESULT ran_on_host=0 check=pass`
! - what the kernel does: the statement `gps(local_idx)%loc = [i, j, k]` assigns a 3-element array to a component of an
!   element that only this iteration writes (local_idx comes from an atomic capture, OpenMP 5.2 §15.8.4 p.311: atomic regions
!   on one location exclude each other across teams)
! - same cause as the C reduction: flang lowers the array constructor to a heap temporary inside the kernel (device FIR
!   `fir.allocmem !fir.array<3xi32> {bindc_name = ".tmp.arrayctor"}` and the inlined device malloc in the assembly, 51 global
!   atomics against 1 in the element-wise kernel: results/student-repro/ir/), and the temporary is allocated and freed by
!   AFAR's OpenMP device allocator (the LLVM libc GPU allocator), whose `free` appears not to release the earlier stores to
!   the block before the block can be handed out again (the evidence, the assembly and the fence cure are in the C file). The
!   cure of the C file, a release fence or `omp flush` before `free`, cannot be written here: the `free` of an
!   array-constructor temporary is generated by the compiler at the end of the statement. Workarounds for the allocator as
!   shipped: no heap temporary in the kernel, which is the constructor-free whole-array store
!   (controls/afar-first-use-malloc-student-nocons.f90: `tmp3(1) = i; ...; loc = tmp3`) and the element-wise stores
!   (controls/afar-first-use-malloc-student-elem.f90), both correct and allocating nothing; and `-fstack-arrays` (every array
!   temporary of the program on the stack whatever its size, a program-wide cost that is unsafe for large temporaries; the
!   maintainer's runs, results/student-repro/variants3.txt: 0 of 4, not row-backed). Rates in this file's rows
!   (results/malloc-dd/observation_rows.jsonl): 7 of 10 repeats fail (harness row, HSA_XNACK=1, 2 trials per run); the
!   maintainer's runs saw duplicated cells equal to missing cells equal to bad records, a few to a few dozen of 11,316,224,
!   mostly in trial 1 (not row-backed); the two controls pass 10 of 10 each
! - upstream fix test (details, patch text, mechanism, validity check and rows in the C file): AFAR 24.3.0's own amdgcn libc
!   rebuilt from the commit it was built from (ROCm/llvm-project 3ba19712e9fbf709f6c93d33394211ed4eeec8a7) and linked into
!   this program with `-Xoffload-linker <build>/libc/lib/libc.a`; this program (orig.f90, args `10 50 6`, 6 trials per
!   launch), 5 launches per variant, MI300A, HSA_XNACK=1 (rows results/malloc-dd/libc_fortran_rows.jsonl, tuolumne1028): stock
!   libc 4 of 5 launches damaged (5 of 30 trials), rebuilt unmodified (ctl) 4 of 5 (6 of 30; its executable is byte-identical
!   to the stock one), with a release fence before the slab bit clear in Slab::deallocate (rel) 0 of 5 (0 of 30), with that
!   fence and an acquire fence after the claim (relacq) 0 of 5 (0 of 30); the maintainer's runs: stock 5 of 5 (8 of 30), ctl
!   5 of 5 (5 of 30), rel 0 of 5, relacq 0 of 5 (results/malloc-dd/libcab/f_rows3.txt). The Fortran program was run against
!   rel and relacq only. No source workaround is needed once a libc with the fence ships. Not shown: other AFAR releases,
!   other GPUs, a libc test suite, a trace of the write-backs; the C file lists the rest
! - other runs: MI250X (Tioga) and HSA_XNACK=0 showed no failure in the maintainer's runs of the original
!   (results/student-repro/sweep.txt, variants*.txt; no row file here, not row-backed); this is not shown to be absent there,
!   and the C reduction fails 1 of 8 launches at HSA_XNACK=0
! - same-compiler controls: controls/afar-first-use-malloc-student-elem.f90 (element-wise stores) and
!   controls/afar-first-use-malloc-student-nocons.f90 (whole-array store without a constructor), one change each from this
!   file, correct on afar (AFAR 24.3.0); rows results/malloc-dd/observation_rows.jsonl
! - gate: one cell, `kbody|afar-first-use-malloc-student|afar|1`, went through the gate twice (rows
!   results/malloc-dd/observation_rows.jsonl). First run: a, b and d on tuolumne1021 and c on tuolumne1028 all failed. Second
!   run: a and b failed, c and d were correct_on_device. It reproduced in a-d in one of two gate runs; with the run-to-run
!   variation of the program (7 of 10 repeats) this is a non-deterministic failure
! - legality: the rules (offload.engine.rules and the race rule, offload.engine.prerun.rules_witness) accept it, the claimed slot
!   being unique to the iteration (an atomic capture of a counter that goes up by 1, a shared counter, no other access to it);
!   that witness does not model `has_device_addr`. AFAR's front end accepts it and is the compiler under test, so it is no
!   witness; no Fortran front end of another family was run (CCE ftn and NVHPC not run); GCC is no witness. So the program is
!   `unspecified` and the statement above is an observation; the C reduction, whose legality does not depend on this clause
!   (it is an implementation contract, no OpenMP rule), is the finding
module m_repro
    implicit none
    integer, parameter :: m = 439, n = 329, p = 329, buff = 10, layers = 3
    type integer_field
        integer, pointer, dimension(:,:,:) :: sf => null()
    end type integer_field
    type ghost_point
        integer, dimension(3) :: loc
        real(8), dimension(3) :: ip_loc
        integer, dimension(3) :: ip_grid
        real(8), dimension(2, 2, 2) :: interp_coeffs
        logical :: interp_valid
        integer :: ib_patch_id
        real(8) :: levelset
        real(8), dimension(3) :: levelset_norm
        logical :: slip
        integer, dimension(3) :: DB
        integer :: x_periodicity, y_periodicity, z_periodicity
    end type ghost_point
    type(integer_field) :: markers
    type(ghost_point), allocatable, dimension(:) :: gps
    !$omp declare target(markers, gps)
contains
    subroutine s_find_ghost_points()
        integer :: i, j, k, ii, jj, kk, count, local_idx, id
        logical :: is_gp
        count = 0
        !$omp target teams distribute parallel do collapse(3) private(i, j, k, ii, jj, kk, is_gp, local_idx, id) &
        !$omp& map(to: count) has_device_addr(gps)
        do i = 0, m
            do j = 0, n
                do k = 0, p
                    if (markers%sf(i, j, k) /= 0) then
                        is_gp = .false.
                        search: do ii = i - layers, i + layers
                            do jj = j - layers, j + layers
                                do kk = k - layers, k + layers
                                    if (markers%sf(ii, jj, kk) == 0) then
                                        is_gp = .true.; exit search
                                    end if
                                end do
                            end do
                        end do search
                        if (is_gp) then
                            !$omp atomic capture
                            count = count + 1
                            local_idx = count
                            !$omp end atomic
                            gps(local_idx)%loc = [i, j, k]
                            id = markers%sf(i, j, k)
                            gps(local_idx)%ib_patch_id = id
                            gps(local_idx)%x_periodicity = 0; gps(local_idx)%y_periodicity = 0; gps(local_idx)%z_periodicity = 0
                            gps(local_idx)%slip = .false.
                            gps(local_idx)%DB(1) = 0; gps(local_idx)%DB(2) = 0; gps(local_idx)%DB(3) = 0
                        end if
                    end if
                end do
            end do
        end do
    end subroutine s_find_ghost_points
end module m_repro

program amd_atomic_capture_repro
    use omp_lib
    use m_repro
    implicit none
    integer :: tot, host_flag, spacing, nper, trials, t, q, i, j, k, a, b, c, id, num_gps, bad, dup, missing
    integer, allocatable :: hits(:, :, :)
    character(len=16) :: arg
    spacing = 10
    nper = 50
    trials = 2
    tot = 0; host_flag = 1
    !$omp target map(from: host_flag)
    host_flag = merge(1, 0, omp_is_initial_device())
    !$omp end target
    allocate (markers%sf(-buff:m + buff, -buff:n + buff, -buff:p + buff), hits(0:m, 0:n, 0:p))
    markers%sf = 0; id = 0
    do a = 0, nper - 1; do b = 0, nper - 1; do c = 0, nper - 1
        if (8 + a*spacing > m - 8 .or. 8 + b*spacing > n - 8 .or. 8 + c*spacing > p - 8) cycle
        id = id + 1
        do k = -4, 4; do j = -4, 4; do i = -4, 4
            if (i*i + j*j + k*k <= 16) markers%sf(8 + a*spacing + i, 8 + b*spacing + j, 8 + c*spacing + k) = id
        end do; end do; end do
    end do; end do; end do
    hits = 0; num_gps = 0
    do k = 0, p; do j = 0, n; do i = 0, m
        if (markers%sf(i, j, k) /= 0) then
            if (any(markers%sf(i - layers:i + layers, j - layers:j + layers, k - layers:k + layers) == 0)) num_gps = num_gps + 1
        end if
    end do; end do; end do
    allocate (gps(num_gps))
    !$omp target enter data map(always, alloc: markers%sf)
    !$omp target update to(markers%sf)
    !$omp target enter data map(alloc: gps)
    print '(A,I0,A,I0)', 'spheres ', id, '  ghost cells ', num_gps
    do t = 1, trials
        call s_find_ghost_points()
        !$omp target update from(gps)
        hits = 0; bad = 0
        do q = 1, num_gps
            if (any(gps(q)%loc < 0) .or. gps(q)%loc(1) > m .or. gps(q)%loc(2) > n .or. gps(q)%loc(3) > p) then
                bad = bad + 1; cycle
            end if
            hits(gps(q)%loc(1), gps(q)%loc(2), gps(q)%loc(3)) = hits(gps(q)%loc(1), gps(q)%loc(2), gps(q)%loc(3)) + 1
            if (markers%sf(gps(q)%loc(1), gps(q)%loc(2), gps(q)%loc(3)) /= gps(q)%ib_patch_id) bad = bad + 1
        end do
        dup = count(hits > 1); missing = num_gps - count(hits > 0)
        print '(A,I3,A,I0,A,I0,A,I0)', 'trial ', t, ': bad records ', bad, '  duplicated cells ', dup, '  missing cells ', missing
        tot = tot + bad + dup + missing
    end do
    print '(a,i0,a,a)', 'RESULT ran_on_host=', host_flag, ' check=', merge('pass', 'fail', tot == 0)
end program amd_atomic_capture_repro
