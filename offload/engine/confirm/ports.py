"""C/Fortran port equivalence for hand derivations (registry RUL-PORT-DERIVATION).

A Fortran catalog program's hand derivation counts for its C port when
the port computes and checks the same value from the same construct. The
equivalence is recorded per port in catalog/omp/port_equivalence.yaml
(``write``) and checked by a test (``problems``): the port is
offload.engine.f2c's translation of that Fortran program (offload.engine.c_gen:
same data, oracle and output contract), the atom has no C source edit
(``c_gen.C_EDITS``) and no C relabelling (``c_gen.C_LABELS``), both
programs are legal with the same primary atom, evidence and expectation,
and the Fortran program carries a derivation. A port without an entry
keeps its own sources (provisional or derived)."""
from __future__ import annotations

from pathlib import Path

import functools

import yaml

from offload.engine.confirm import programs as P

ROOT = Path(__file__).resolve().parent.parent.parent.parent
DATA = ROOT / "catalog" / "omp" / "port_equivalence.yaml"


def _derivation(src: str) -> str | None:
    from offload.engine import expected as E
    ev = E.derivation_evidence(src)
    return ev.value if ev.status == "value" else None


def candidates() -> list[dict]:
    """Every C port that meets the equivalence conditions."""
    from offload.engine import c_gen
    out = []
    for v in c_gen.C_VERSIONS:
        for cid, cprog in sorted(P._catalog(v, "c").items()):
            if not cprog.legal:
                continue
            fid = P.port_of(cid)
            fprog = P.catalog_program(fid) if fid else None
            if fprog is None or not fprog.legal:
                continue
            why = problems_of(cprog, fprog)
            if why:
                continue
            out.append({"c": cid, "fortran": fid,
                        "atom": cprog.primary_atom,
                        "value": _derivation(fprog.source),
                        "basis": "offload.engine.f2c translation of the Fortran "
                                 "program (same data, oracle and output "
                                 "contract); no C edit or relabel"})
    return out


def problems_of(cprog, fprog) -> list[str]:
    from offload.engine import c_gen
    errs = []
    if cprog.primary_atom != fprog.primary_atom:
        errs.append("primary atom differs")
    if cprog.primary_atom in c_gen.C_EDITS:
        errs.append("C source edit")
    if cprog.primary_atom in c_gen.C_LABELS:
        errs.append("C relabelling")
    if cprog.evidence != fprog.evidence or cprog.expect != fprog.expect:
        errs.append("evidence or expectation differs")
    if _derivation(fprog.source) is None:
        errs.append("the Fortran program has no derivation")
    return errs


def write(path: Path = DATA) -> int:
    rows = candidates()
    Path(path).write_text(
        "# (ruling B): C ports whose Fortran "
        "program's\n# hand derivation counts for them "
        "(offload/engine/confirm/ports.py).\n"
        "# Generated by `tools/confirm.py ports --write`; checked by "
        "tests/confirm/test_confirm_ports.py.\n"
        + yaml.safe_dump({"ports": rows}, sort_keys=False, width=100))
    return len(rows)


@functools.lru_cache(maxsize=None)
def _entries(path: str, mtime: float) -> dict:
    data = yaml.safe_load(Path(path).read_text()) or {}
    return {e["c"]: e for e in data.get("ports") or []}


def load(path: Path = DATA) -> dict:
    """C id -> entry (read once per version of the file; do not change it)."""
    if not Path(path).is_file():
        return {}
    return _entries(str(path), Path(path).stat().st_mtime)


def derivation_for(c_id: str) -> tuple[str, str] | None:
    """(value, Fortran id) of the derivation a recorded port inherits."""
    e = load().get(c_id)
    if e is None:
        return None
    f = P.catalog_program(e["fortran"])
    if f is None:
        return None
    v = _derivation(f.source)
    return (v, e["fortran"]) if v else None
