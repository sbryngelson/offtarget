"""Confirmed catalog bugs without a finding.

A catalog cell the confirmer calls a bug (``engine.BUG_VERDICTS``) whose
dedupe found no finding, duplicate or related ("dedupe: new failure
signature"), is backlog: the support tables and the dashboard count it as
a confirmed failure, but no reproducer was reported. ``groups`` groups
such cells by the confirmer's failure signature (front end, outcome group
and the cause: an ICE's message, a rejection's diagnostic key or link
symbol, or, for a run-time failure and a generic ICE message, the
catalog program across versions); ``catalog/unlinked_bugs.yaml`` records
why each remaining group has no finding, and the test
(tests/confirm/test_confirm_backlog.py) fails when a group without a recorded
reason appears or a recorded group changes size, so the backlog cannot
grow silently. ``render`` writes data/reports/unlinked-bugs.md."""
from __future__ import annotations

import json
import re
from collections import Counter
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent.parent.parent
BATCH = ROOT / "results" / "confirm" / "batch_full.jsonl"
DATA = ROOT / "catalog" / "unlinked_bugs.yaml"
DOC = ROOT / "data" / "reports" / "unlinked-bugs.md"
BUG = ("compiler_bug", "copy_mode_failure", "unified_memory_failure",
       "arch_specific")
GENERIC_ICE = re.compile(r"PLEASE submit a bug report|clang frontend "
                         r"command failed|stack dump", re.I)


def unlinked(batch: Path = BATCH) -> list[dict]:
    """The catalog results with a bug verdict and no finding (duplicate
    or related)."""
    out = []
    for line in Path(batch).read_text().splitlines():
        d = json.loads(line)
        if d["case"]["program"]["kind"] != "catalog" or \
                d["verdict"] not in BUG:
            continue
        if d.get("findings") or d.get("related"):
            continue
        out.append(d)
    return out


def _n(text: str) -> str:
    return re.sub(r"0x[0-9a-fA-F]+|\d+", "N", text)


def key(d: dict) -> str:
    """family | lang | outcome group | cause."""
    from offload.engine.confirm import findings as FI
    from offload.engine.confirm.facts import diagnostic_key
    from offload.engine.confirm.machines import family_of
    c = d["case"]
    pid = c["program"]["ident"]
    prog = re.sub(r"^(omp|acc)\d\d-", r"\1*-", pid)
    g = FI.group(c["outcome"], c["reason"])
    r = c.get("reason") or ""
    if g == "rejected":
        m = re.search(r"undefined (?:symbol:|reference to) ?`?([^\s']+)", r)
        u = re.search(r"undeclared function '(\w+)'", r)
        if m and r.startswith("link"):
            cause = "link " + m.group(1)
        elif u:
            cause = f"undeclared function {u.group(1)}"
        else:
            k = diagnostic_key(r)
            cause = k if re.fullmatch(r"ftn-\d+", k) else _n(k)
    elif g == "ice" and not GENERIC_ICE.search(r):
        cause = _n(FI.strip_site(FI.normalize(r)))[:100]
    else:
        cause = prog
    return f"{family_of(c['toolchain'])}|{c['program']['lang']}|{g}|{cause}"


def groups(results: list[dict]) -> dict[str, list[dict]]:
    out: dict[str, list[dict]] = {}
    for d in results:
        out.setdefault(key(d), []).append(d)
    return dict(sorted(out.items()))


def load(path: Path = DATA) -> dict:
    d = yaml.safe_load(Path(path).read_text()) or {}
    if d.get("version") != 1:
        raise ValueError(f"{path}: unknown version")
    return d


def check(gs: dict[str, list[dict]], data: dict) -> list[str]:
    """Problems: a group with no recorded reason, a recorded group whose
    cell count changed, a recorded group that no longer exists."""
    rec = {g["key"]: g for g in data.get("groups") or []}
    out = []
    for k, ds in gs.items():
        if k not in rec:
            out.append(f"new backlog group (no finding, no recorded "
                       f"reason): {k} ({len(ds)} cells)")
        elif rec[k]["cells"] != len(ds):
            out.append(f"{k}: {len(ds)} cells, recorded {rec[k]['cells']}")
    for k in rec:
        if k not in gs:
            out.append(f"recorded group no longer in the backlog: {k}")
    return out


def summary(ds: list[dict]) -> dict:
    c = ds[0]["case"]
    return {"cells": len(ds),
            "programs": sorted({d["case"]["program"]["ident"] for d in ds}),
            "toolchains": sorted({d["case"]["toolchain"] for d in ds}),
            "verdicts": dict(Counter(d["verdict"] for d in ds)),
            "rules": dict(Counter(d["rule"] for d in ds)),
            "example": c["case_id"], "reason": (c.get("reason") or "")[:200]}


def render(gs: dict[str, list[dict]], data: dict) -> str:
    rec = {g["key"]: g for g in data.get("groups") or []}
    n = sum(map(len, gs.values()))
    lines = [
        "# Confirmed catalog bugs without a finding",
        "",
        "Generated by `python3 -I tools/confirm.py backlog --write` from "
        "results/confirm/batch_full.jsonl and catalog/unlinked_bugs.yaml "
        "(offload/engine/confirm/backlog.py). A cell is listed when the "
        "confirmer calls it a bug (compiler_bug, unified_memory_failure, "
        "copy_mode_failure, arch_specific) and its dedupe found no finding, "
        "duplicate or related. tests/confirm/test_confirm_backlog.py fails when a "
        "group appears without a recorded reason or a group's size changes.",
        "",
        "## How the backlog was closed",
        "",
        data.get("history", "").strip(),
        "",
        "## Promoted and linked groups",
        "",
        "| group (family, lang, outcome, cause) | cells | outcome |",
        "|---|---|---|",
        *[f"| `{g['key']}` | {g['cells']} | {g['outcome']} |"
          for g in data.get("closed") or []],
        "",
        f"## Remaining: {n} cells in {len(gs)} groups",
        "",
        "| group | cells | verdicts | programs | example | why no finding |",
        "|---|---|---|---|---|---|",
    ]
    for k, ds in gs.items():
        s = summary(ds)
        why = (rec.get(k) or {}).get("why", "**no recorded reason**")
        lines.append(
            f"| `{k}` | {s['cells']} | "
            + ", ".join(f"{v} {c}" for v, c in s["verdicts"].items())
            + f" | {', '.join(s['programs'])} | `{s['example']}` | "
            f"{why} |")
    return "\n".join(lines) + "\n"
