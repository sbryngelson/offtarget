"""OpenMP 5.0 against 5.2: write docs/tooling/omp5-vs-52.md and docs/tooling/omp-50-vs-52-results.md.

    python3 -I tools/derive/omp50_delta.py delta     # docs/tooling/omp5-vs-52.md
    python3 -I tools/derive/omp50_delta.py results   # docs/tooling/omp-50-vs-52-results.md
        [--results results/matrix.jsonl]

``delta`` renders the spec comparison from the catalog (slice_atoms at 50 and 52,
clauses.yaml forms, spec_overrides.yaml, rules.yaml spec entries) and
catalog/omp/omp50_delta.yaml (first versions, spelling differences, absent and
changed rules, 5.0 programs that 5.2 removed or changed). ``results`` reads the
matrix rows of versions 50 and 52 at HSA_XNACK=1 and shows each toolchain's 5.0
and 5.2 outcome side by side per atom (legal programs) and per rule (illegal
variants), flagging cells where a toolchain is right at one version only. It also
checks that a 5.0 program with a body byte-identical to its 5.2 program has the
same outcome; a difference is a finding."""
import argparse
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(ROOT))

from offload.engine.catalog import slice_atoms  # noqa: E402
from offload.engine.gen import generate  # noqa: E402
from offload.engine.mutate import body_sha  # noqa: E402
from offload.engine.report import atom_citation  # noqa: E402
from offload.engine.run_matrix import version_flags  # noqa: E402

DELTA = ROOT / "catalog" / "omp" / "omp50_delta.yaml"
RULES = ROOT / "catalog" / "omp" / "rules.yaml"
OVERRIDES = ROOT / "catalog" / "omp" / "spec_overrides.yaml"
DOC_DELTA = ROOT / "docs" / "tooling" / "omp5-vs-52.md"
DOC_RESULTS = ROOT / "docs" / "tooling" / "omp-50-vs-52-results.md"
MATRIX = ROOT / "results" / "matrix.jsonl"
TOOLCHAINS = ("afar", "cce19", "cce20", "cce21")
TC_NAME = {"afar": "AFAR", "cce19": "CCE 19", "cce20": "CCE 20",
           "cce21": "CCE 21"}


def _md(text) -> str:
    return " ".join(str(text).split()).replace("|", "\\|")


def load_delta(path: Path = DELTA) -> dict:
    return yaml.safe_load(Path(path).read_text())


def rule_entries(path: Path = RULES) -> list[dict]:
    return yaml.safe_load(Path(path).read_text())["rules"]


def programs(version: int) -> dict:
    """(legal: primary atom | illegal: rule stem) -> Program."""
    out = {}
    for p in generate(slice_atoms(version), version):
        if p.scope != "device":  # Host+device patterns
            continue
        key = p.primary_atom if p.legal else p.violates.split("-", 1)[1]
        out[key] = p
    return out


# --- docs/tooling/omp5-vs-52.md --------------------------------------------------------------

def render_delta(delta: dict | None = None) -> str:
    delta = delta or load_delta()
    a50, a52 = set(slice_atoms(50)), set(slice_atoms(52))
    since = delta["atoms_since"]
    spelling = delta["spelling"]
    # the 5.0 catalog is Fortran: the C rules (lang: c) are not
    # part of the 5.0 delta
    rules = [e for e in rule_entries() if 52 in e["spec"]
             and e.get("lang") != "c"]
    absent, changed = delta["absent_rules"], delta["changed_rules"]
    p50, p52 = programs(50), programs(52)
    same = sorted(k for k in p50 if k in p52
                  and body_sha(p50[k].source) == body_sha(p52[k].source))
    differ = sorted(k for k in p50 if k in p52 and k not in same)
    n_same_rules = sum(1 for e in rules if 50 in e["spec"]
                       and e["id"] not in changed)
    out = [
        "# OpenMP 5.0 against 5.2 for the slice",
        "",
        "Generated by `tools/derive/omp50_delta.py delta` from the catalog and "
        "[catalog/omp/omp50_delta.yaml](../catalog/omp/omp50_delta.yaml); "
        "do not edit. Status: **provisional** (spec-derived; not "
        "owner-reviewed). Citations are section and printed page of "
        "spec/openmp/openmp-5.0.pdf, -5.1.pdf and -5.2.pdf; the history "
        "quotes are from the Features History appendices.",
        "",
        "## Summary",
        "",
        f"- 5.2 slice atoms: {len(a52)}; in 5.0: {len(a52 & a50)}; new in "
        f"5.1: {sum(1 for e in since.values() if e['since'] == 51)}; new in "
        f"5.2: {sum(1 for e in since.values() if e['since'] == 52)}. No "
        "5.0 atom of the slice was removed by 5.2 "
        f"({len(a50 - a52)} atoms only in 5.0).",
        f"- 5.0 atoms whose spelling, program shape or meaning differs from "
        f"5.2: {len(spelling)} (table below).",
        f"- 5.0 programs (`omp50-...`): {sum(p.legal for p in p50.values())}"
        f" legal, {sum(not p.legal for p in p50.values())} illegal variants;"
        f" {len(same)} have the same body as their 5.2 program (only the "
        f"header differs), {len(differ)} differ: "
        + ", ".join(f"`{k}`" for k in differ) + ".",
        f"- 5.2 restriction rules: {len(rules)}; with a 5.0 counterpart: "
        f"{sum(1 for e in rules if 50 in e['spec'])} ({n_same_rules} the "
        f"same requirement, {len(changed)} different in substance); absent "
        f"from 5.0: {len(absent)}.",
        f"- Clauses 5.0 does not allow on a slice directive although 5.2 "
        f"does: {len(delta['clause_rules'])} families (table below).",
        f"- AFAR compiles the 5.0 programs with "
        f"`{version_flags('afar', 50)}`; CCE has no version flag.",
        "",
        "## Atoms",
        "",
        "First version of every 5.2 slice atom. `<= 5.0`: the atom is in "
        "the 5.0 slice (its 5.0 grammar form, catalog/omp/clauses.yaml, or "
        "the 5.2 form where the syntax is unchanged); the 5.0 citation is "
        "the clause or construct section.",
        "",
        "| atom | since | 5.0 citation | 5.2 citation | 5.0 spelling / note |",
        "|---|---|---|---|---|"]
    for atom in sorted(a52):
        e = since.get(atom)
        c52 = atom_citation(atom, 52)[0]
        if e is None:
            c50 = atom_citation(atom, 50)[0]
            sp = spelling.get(atom)
            note = f"{sp['spelling50']} (5.2: {sp['spelling52']})" \
                if sp else ""
            out.append(f"| `{atom}` | <= 5.0 | {_md(c50)} | {_md(c52)} | "
                       f"{_md(note)} |")
        else:
            why = e.get("quote") or e.get("note", "")
            out.append(f"| `{atom}` | {e['since'] // 10}.{e['since'] % 10} | "
                       f"{_md(e['cite50'])} (absent) | {_md(c52)} | "
                       f"{_md(e['cite'])}: " + (f'"{_md(why)}"' if
                                                 e.get("quote") else _md(why))
                       + " |")
    out += ["", "## Spelling, program shape and meaning differences", "",
            "| atom | 5.0 | 5.2 | 5.0 citation | 5.2 citation | note |",
            "|---|---|---|---|---|---|"]
    for atom, e in sorted(spelling.items()):
        out.append(f"| `{atom}` | {_md(e['spelling50'])} | "
                   f"{_md(e['spelling52'])} | {_md(e['cite50'])} | "
                   f"{_md(e['cite'])} | {_md(e['note'])} |")
    out += ["", "## Clauses not allowed at 5.0", "",
            "Spec overrides with `since` 51/52 (catalog/omp/"
            "spec_overrides.yaml) or TableGen version ranges.", "",
            "| clause | directives | since | 5.0 citation | later citation "
            "| note |", "|---|---|---|---|---|---|"]
    for e in delta["clause_rules"]:
        out.append(f"| `{e['clause']}` | {', '.join(e['directives'])} | "
                   f"{e['since'] // 10}.{e['since'] % 10} | "
                   f"{_md(e['cite50'])} | {_md(e['cite'])} | "
                   f"{_md(e['note'])} |")
    out += ["", "## Restrictions", "",
            "Each 5.2 rule of catalog/omp/rules.yaml: its 5.0 counterpart "
            "(the `50` entry quotes the 5.0 sentence), or why there is none. "
            "**same**: the same requirement in other words (the predicate is "
            "the 5.2 one); **changed**: the 5.0 sentence differs in "
            "substance; **absent**: no 5.0 rule (no illegal 5.0 variant).",
            "", "| rule | 5.0 | 5.0 citation | 5.2 citation | note |",
            "|---|---|---|---|---|"]
    for e in rules:
        stem, s52 = e["id"], e["spec"][52]["citation"]
        if 50 in e["spec"]:
            kind = "changed" if stem in changed else "same"
            note = changed.get(stem, "")
            out.append(f"| `{stem}` | {kind} | {e['spec'][50]['citation']} "
                       f"| {s52} | {_md(note)} |")
        else:
            a = absent[stem]
            out.append(f"| `{stem}` | absent | {a['cite50']} | {s52} | "
                       f"{_md(a['reason'])} |")
    out += ["", "## Legal 5.0 programs that 5.2 removed, tightened, "
            "deprecated or changed in meaning", "",
            "| construct | kind | 5.0 citation | later citation | note |",
            "|---|---|---|---|---|"]
    for e in delta["legal50_not52"]:
        out.append(f"| {_md(e['construct'])} | {e['kind']} | {e['cite50']} "
                   f"| {e['cite']} | {_md(e['note'])} |")
    out += ["", "Kinds: **removed** (legal 5.0, illegal 5.2), **tightened** "
            "(unspecified behaviour in 5.0, a restriction in 5.2), "
            "**meaning** (legal at both, conforming behaviour differs), "
            "**deprecated** (legal at both, deprecated by 5.2 or earlier), "
            "**reverse** (legal 5.2, illegal 5.0: a 5.2 program a 5.0 "
            "compiler must reject).",
            ""]
    return "\n".join(out) + "\n"


# --- docs/tooling/omp-50-vs-52-results.md -----------------------------------------------------

def _right(r: dict) -> bool | None:
    """True if the cell is what a conforming toolchain gives (legal: correct
    on the device or a clean unobservable run; illegal: rejected), False
    otherwise, None for a harness error."""
    if r["outcome"] == "harness_error":
        return None
    if r["legal"]:
        return r["outcome"] in ("correct_on_device", "unobservable")
    return r["outcome"] == "rejected"


def _short(r: dict) -> str:
    o = r["outcome"]
    if not r["legal"]:
        return "rejected" if o == "rejected" else f"not rejected ({o})"
    return o


def compare(rows: list[dict], xnack: int = 1) -> dict:
    """{key: {toolchain: {50: row, 52: row}}} for the legal programs (key:
    primary atom) and illegal variants (key: rule stem) of both versions."""
    out: dict = defaultdict(lambda: defaultdict(dict))
    for r in rows:
        if r["version"] not in (50, 52) or r["xnack"] != xnack:
            continue
        key = r["primary_atom"] if r["legal"] else \
            r["violates"].split("-", 1)[1]
        out[(r["legal"], key)][r["toolchain"]][r["version"]] = r
    return out


# Why a toolchain is right at one version only (the programs differ: the
# spelling table of docs/tooling/omp5-vs-52.md); checked against the reasons in
# the matrix rows.
RESULT_NOTES = {
    "omp.clause.linear.ref":
        "CCE 19/20 accept the 5.0 `linear(ref(x))` and reject the 5.2 "
        "`linear(x: ref)` (ftn-297, the modifier read as a variable); CCE 21 "
        "accepts both. AFAR rejects the 5.0 program with the 5.2 rule (a ref "
        "item must be assumed-shape, polymorphic or allocatable), which "
        "reverses 5.0's (data/findings/afar-linear-ref-omp50.f90), and the "
        "5.2 one as `omp.declare_simd` not yet implemented",
    "omp.clause.linear.uval":
        "CCE 19/20 accept the 5.0 `linear(uval(x))`, reject the 5.2 "
        "`linear(x: uval)` (ftn-297); AFAR: `omp.declare_simd` not yet "
        "implemented at both",
    "omp.clause.linear.val":
        "the 5.0 program is declare simd `linear(val(x))` (5.0 allows no "
        "modifier on loop constructs), accepted by CCE 19/20/21; the 5.2 "
        "program `linear(x: val, step(1))` on parallel do is rejected by CCE "
        "19/20 (ftn-113) and CCE 21 (ftn-1510); AFAR: declare simd not yet "
        "implemented (5.0), an ICE (5.2)",
    "omp.clause.uses_allocators.traits":
        "CCE 19/20/21 read the 5.0 `uses_allocators(my_alloc(my_traits))` "
        "as a function reference (ftn-451, ftn-1473) and accept the 5.2 "
        "`uses_allocators(traits(my_traits): my_alloc)` "
        "(data/findings/cce-uses-allocators-traits-omp50.f90); AFAR: "
        "uses_allocators not yet implemented at both",
}


def render_results(rows: list[dict]) -> str:
    p50, p52 = programs(50), programs(52)
    same_body = {k for k in p50 if k in p52
                 and body_sha(p50[k].source) == body_sha(p52[k].source)}
    cmp = compare(rows)
    tcs = [t for t in TOOLCHAINS
           if any(t in by for by in cmp.values())]
    only = Counter()
    finding_rows = []
    n50 = Counter((r["toolchain"], r["outcome"]) for r in rows
                  if r["version"] == 50 and r["xnack"] == 1 and r["legal"])
    lines = []
    for legal in (True, False):
        keys = sorted(k for lg, k in cmp if lg == legal)
        if legal:
            lines += ["## Legal programs (per atom)", ""]
        else:
            lines += ["", "## Illegal variants (per rule; right = "
                      "rejected)", ""]
        lines += ["| " + ("atom" if legal else "rule") + " | same body | "
                  + " | ".join(f"{TC_NAME[t]} 5.0 | {TC_NAME[t]} 5.2"
                               for t in tcs) + " | right at one version "
                  "only |",
                  "|---|---|" + "---|---|" * len(tcs) + "---|"]
        for k in keys:
            by = cmp[(legal, k)]
            cells, flags = [], []
            for t in tcs:
                a, b = by[t].get(50), by[t].get(52)
                cells += [_short(a) if a else "", _short(b) if b else ""]
                if a and b:
                    ra, rb = _right(a), _right(b)
                    if ra is not None and rb is not None and ra != rb:
                        flags.append(f"{TC_NAME[t]}: "
                                     + ("5.0" if ra else "5.2"))
                        only[(t, "5.0" if ra else "5.2")] += 1
                    if k in same_body and a["outcome"] != b["outcome"]:
                        finding_rows.append((k, legal, t, a, b))
            same = "-" if k not in p50 or k not in p52 else (
                "yes" if k in same_body else "no")
            lines.append(f"| `{k}` | {same} | "
                         + " | ".join(cells) + f" | {'; '.join(flags)} |")
    head = [
        "# OpenMP 5.0 and 5.2 results side by side",
        "",
        "Generated by `tools/derive/omp50_delta.py results` from "
        "results/matrix.jsonl; do not edit. Headline mode HSA_XNACK=1, -O2, "
        "one repeat for the 5.0 programs (5.2: the runs). AFAR "
        "compiles 5.0 programs with `-fopenmp-version=50` and 5.2 programs "
        "with its default; CCE has no version flag, so a 5.0 program whose "
        "body is the 5.2 program's (`same body`: only the header comment "
        "differs) is the same compile on CCE. Raw harness outcomes (the "
        "support table adds the evidence and audit columns).",
        "",
        "## Counts",
        "",
        "Legal 5.0 programs at HSA_XNACK=1, raw outcomes:",
        "",
        "| toolchain | " + " | ".join(
            ["correct_on_device", "unobservable", "rejected",
             "wrong_answer", "fell_back_to_host", "accepted_ignored",
             "harness_error"]) + " |",
        "|---|" + "---|" * 7]
    for t in tcs:
        head.append(f"| {TC_NAME[t]} | " + " | ".join(
            str(n50[(t, o)]) for o in (
                "correct_on_device", "unobservable", "rejected",
                "wrong_answer", "fell_back_to_host", "accepted_ignored",
                "harness_error")) + " |")
    flagged = sorted({k for (lg, k), by in cmp.items() for t in tcs
                      if (a := by[t].get(50)) and (b := by[t].get(52))
                      and None not in (_right(a), _right(b))
                      and _right(a) != _right(b)})
    head += ["", "Cells where a toolchain is right at one version only: "
             + (", ".join(f"{TC_NAME[t]} right only at {v}: {n}"
                          for (t, v), n in sorted(only.items())) or "none")
             + ". Every such program differs between the versions "
             "(docs/tooling/omp5-vs-52.md, spelling table):", ""]
    head += [f"- `{k}`: {RESULT_NOTES.get(k, '(no note)')}." for k in flagged]
    head += ["",
             "## Same body, different outcome (findings)", "",
             "A 5.0 program byte-identical (below its header) to its 5.2 "
             "program whose outcome differs on a toolchain: "
             f"{len(finding_rows)}.", ""]
    if finding_rows:
        head += ["| program | toolchain | 5.0 | 5.2 | 5.0 reason | 5.2 "
                 "reason |", "|---|---|---|---|---|---|"]
        for k, legal, t, a, b in finding_rows:
            head.append(f"| `{a['program_id']}` | {TC_NAME[t]} | "
                        f"{_short(a)} | {_short(b)} | "
                        f"{_md(a.get('reason', ''))[:160]} | "
                        f"{_md(b.get('reason', ''))[:160]} |")
    head.append("")
    return "\n".join(head + lines) + "\n"


def read_rows(path: Path) -> list[dict]:
    return [json.loads(line) for line in Path(path).read_text().splitlines()
            if line.strip()]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("delta")
    r = sub.add_parser("results")
    r.add_argument("--results", type=Path, default=MATRIX)
    r.add_argument("--out", type=Path, default=DOC_RESULTS)
    args = ap.parse_args(argv)
    if args.cmd == "delta":
        DOC_DELTA.write_text(render_delta())
        print(f"wrote {DOC_DELTA}")
    else:
        args.out.write_text(render_results(read_rows(args.results)))
        print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
