module gen_mod
  use openacc
  implicit none
  contains
    subroutine dev_twice(x, y, m, hf)
      integer, intent(in) :: m
      integer :: x(m), y(m), hf
      integer :: k
      !$acc parallel loop deviceptr(x, y) copy(hf)
      do k = 1, m
        if (k == 1) hf = merge(1, 0, acc_on_device(acc_device_host))
        y(k) = 2*x(k) + 1
      end do
    end subroutine dev_twice
end module gen_mod

program gen_prog
  use openacc, only: acc_device_host, acc_on_device
  use gen_mod
  implicit none
  integer, parameter :: n = 64
  integer, allocatable, target :: a(:), b(:)
  integer :: ref(n)
  integer :: i, host_flag
  logical :: ok
  logical :: pres, shared_mem
  integer :: zc(1)
  allocate(a(n), b(n))
  do i = 1, n
    a(i) = i
    b(i) = 0
    ref(i) = 2*i + 1
  end do
  host_flag = 1
  pres = .true.
  zc = 0
  !$acc serial copyin(zc)
    zc(1) = 1
  !$acc end serial
  shared_mem = zc(1) == 1
  !$acc data copyin(a) copyout(b)
    !$acc host_data use_device(a, b)
      call dev_twice(a, b, n, host_flag)
    !$acc end host_data
  !$acc end data
  ok = all(b == ref) .and. pres
  print '(a,i0,a,a)', 'RESULT ran_on_host=', host_flag, ' check=', merge('pass', 'fail', ok)
  deallocate(a, b)
end program gen_prog
