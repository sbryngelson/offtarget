#!/usr/bin/env python3
"""Render catalog/gate_queue.yaml (the decisions on the
reproduction gate's review queue) as data/reports/gate-queue.md.
    python3 -I data/evidence/gate_probe/gate_queue.py [--check]"""
from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[3]
SRC = ROOT / "catalog" / "gate_queue.yaml"
DOC = ROOT / "data" / "reports" / "gate-queue.md"


def _cnt(d: dict) -> str:
    return ", ".join(f"{k} x{v}" for k, v in sorted(d.items())) or "-"


def _cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def render(doc: dict) -> str:
    groups = {g["id"]: g for g in doc["groups"]}
    ents = doc["entries"]
    by_v = Counter(e["verdict"] for e in ents)
    by_g = Counter(e["group"] for e in ents)
    out = [
        "# The reproduction gate's review queue, decided", "",
        "Generated by `python3 -I data/evidence/gate_probe/gate_queue.py` from "
        "catalog/gate_queue.yaml (written by data/evidence/gate_probe/build_queue.py "
        "from the decisions and the probe runs); do not edit.", "",
        "The queue: the 97 rerun rows of the gate review whose gate "
        "verdict is not `confirmed` (environment, nondeterministic, not "
        "reproduced). Each was decided legality first (the spec text of "
        "the program's version; no compiler under test, gfortran or gcc as "
        "a witness: for AFAR cells the pre-run check's flang witness is "
        "AFAR's own front end, so the reading of the failing kernel "
        "decides), then determinism (reruns in the gate's environments, "
        "more repeats, the gate's own runner at 1-4 and at 24 concurrent "
        "reruns per node, element traces of the checksum against host "
        "runs of two families).", "",
        "Verdicts: `illegal`, `unspecified` (the row stops counting), "
        "`environment_defect` (a defect whose form needs a named "
        "condition), `nondeterministic_defect` (a defect that shows "
        "intermittently or in a varying form), `ours` (harness, test or "
        "machine; the row counts as what the reruns show), `undecided` "
        "(with what would decide it). `counts as`: `failure` (the cell is a "
        "compiler or runtime failure) or `none`.", "",
        "Provisional (maintainer, 2026-10-26): the gate labelled some "
        "nondeterminism `environment` (a stored row that differs from all "
        "its reruns, values scattering across environments); is "
        "fixing that and will regenerate the queue. So `environment_defect` "
        "versus `nondeterministic_defect` here is provisional, no "
        "`environment_defect` finding was promoted, and each entry records "
        "what this task's repeated runs showed within one environment (one "
        "build directory on one node). Decisions are keyed by the row id "
        "(the cell), so they carry over to the regenerated queue; `k` is "
        "only this queue's order.", "",
        "Scope: a decision applies to its own row (cell) only. It never "
        "propagates to the rows that inherited the gate verdict of its "
        "signature (2,730 rows inherit these 97 verdicts in data/reports/"
        "gate.md): the maintainer's ruling that run-time "
        "failures never inherit. So the counts below are of "
        "these 97 rows, not of the inheriting ones.", "",
        "## Counts", "",
        "| verdict | entries |", "|---|---|"]
    for v in doc["verdicts"]:
        out.append(f"| {v} | {by_v.get(v, 0)} |")
    out += ["", f"Total {len(ents)}; counting as a failure "
            f"{sum(e['counts_as'] == 'failure' for e in ents)}, not "
            f"counting {sum(e['counts_as'] == 'none' for e in ents)}.", "",
            "## Groups", ""]
    for gid, g in groups.items():
        ks = [str(e["k"]) for e in ents if e["group"] == gid]
        out += [f"### {g['title']} (`{gid}`, {by_g[gid]} entries)", "",
                f"- verdict: `{g['verdict']}`; counts as: `{g['counts_as']}`"
                + (f"; finding: `{g['finding']}`" if g.get("finding") else ""),
                f"- entries (queue index): {', '.join(ks)}",
                f"- legality: {g['legality']}",
                f"- determinism: {g['determinism']}",
                f"- action: {g['action']}", ""]
    out += ["## Entries", "",
            "One row per entry: k (the queue index in the gate review's "
            "order: campaign, gate verdict, signature), the cell, campaign, "
            "gate verdict, verdict, reason, action. Observations: the "
            "gate's reruns (a-d), the probe runs (results/t48/batch*), the "
            "gate's own runner at low load and at the gate's load "
            "(results/t48/g4-g6).", "",
            "| k | row id (cell) | campaign | gate | verdict | reason | action |",
            "|---|---|---|---|---|---|---|"]
    for e in ents:
        g = groups[e["group"]]
        obs = (f"gate: {'; '.join(e['gate_reruns'])}. probe: "
               f"{_cnt(e['probe_runs'])}. gate runner low/24: "
               f"{_cnt(e['gate_runner_low_load'])} / "
               f"{_cnt(e['gate_runner_gate_load'])}")
        one = e.get("within_one_environment") or "-"
        reason = (f"{g['title']}: {e['note']}. Stored: {e['stored']}. {obs}. "
                  f"Within one environment: {one}")
        action = f"counts as {e['counts_as']}" + (
            f"; {e['finding']}" if e.get("finding") else "")
        out.append(f"| {e['k']} | `{_cell(e['cell'])}` | {e['campaign']} | "
                   f"{e['gate_verdict']} | {e['verdict']} | {_cell(reason)} "
                   f"| {_cell(action)} |")
    return "\n".join(out) + "\n"


def main() -> int:
    doc = yaml.safe_load(SRC.read_text())
    text = render(doc)
    if "--check" in sys.argv:
        ok = DOC.is_file() and DOC.read_text() == text
        print("current" if ok else "stale")
        return 0 if ok else 1
    DOC.write_text(text)
    print(f"wrote {DOC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
