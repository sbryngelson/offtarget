"""Programs of every kind the confirmer handles: their text, files,
generator Program, C/Fortran port and construct set.

A program set (several files) is one text with a file mark per file:
``!@file <name>.f90`` (offload.engine.fuzz_base.FILE_MARK, the fuzz bundles)
or ``//@file <name>.c``; ``split_files`` returns the files in compile
order. Catalog programs are regenerated by id (the same generator the
matrix ran), fuzz programs from their seed, omp_vv tests are read from
corpus/ (never edited: the confirmer works on copies)."""
from __future__ import annotations

import re
from functools import lru_cache
from pathlib import Path

from offload.engine.confirm.model import ProgramRef

from offload.engine.root import ROOT  # noqa: E402
F_MARK = "!@file "
C_MARK = "//@file "


def split_files(text: str) -> list[tuple[str, str]] | None:
    """[(name, text)] of a program set, None for a single file. Lines
    before the first mark go to the first file."""
    mark = F_MARK if F_MARK in text else C_MARK if C_MARK in text else None
    if mark is None:
        return None
    files: list[list] = []
    head: list[str] = []
    for line in text.splitlines():
        if line.startswith(mark):
            files.append([line[len(mark):].strip(), []])
        elif files:
            files[-1][1].append(line)
        else:
            head.append(line)
    files[0][1] = head + files[0][1]
    return [(n, "\n".join(ls) + "\n") for n, ls in files]


def join_files(files: list[tuple[str, str]]) -> str:
    """One text of a program set (the inverse of ``split_files``)."""
    if len(files) == 1:
        return files[0][1]
    mark = C_MARK if files[0][0].endswith(".c") else F_MARK
    return "".join(f"{mark}{n}\n{t if t.endswith(chr(10)) else t + chr(10)}"
                   for n, t in files)


def lang_of_path(path: str) -> str:
    return "c" if str(path).endswith(".c") else "f90"


def version_of_id(pid: str) -> int:
    m = re.match(r"(?:omp|acc)(\d\d)-", pid)
    return int(m.group(1)) if m else 0


def lang_of_id(pid: str) -> str:
    return "c" if re.match(r"(?:omp|acc)\d\d-c-", pid) else "f90"  


@lru_cache(maxsize=None)
def _catalog(version: int, lang: str) -> dict:
    from offload.engine.catalog import slice_atoms
    from offload.engine.run_matrix import matrix_programs
    atoms = slice_atoms(version, lang=lang)
    return {p.id: p for _, p in matrix_programs(atoms, [version], lang)}


def catalog_program(pid: str):
    """The generator's Program of a catalog id (None if no longer
    generated); a widened catalog program (offload.engine.widen,
    ids ``<model><v>-[c-]w-<slug>``) is one too."""
    from offload.engine import widen
    if widen.is_wide(pid):
        return widen.program(pid)
    try:
        return _catalog(version_of_id(pid), lang_of_id(pid)).get(pid)
    except Exception:
        return None


def catalog_ref(pid: str, prog=None) -> ProgramRef:
    prog = prog or catalog_program(pid)
    if prog is None:
        return ProgramRef("catalog", pid, lang_of_id(pid), version_of_id(pid),
                          "acc" if pid.startswith("acc") else "omp")
    return ProgramRef("catalog", pid, "c" if prog.lang == "c" else "f90",
                      version_of_id(pid), prog.model, prog.legal,
                      tuple(prog.needs), prog.evidence, prog.source,
                      expected=("error_termination" if prog.expect ==
                                "error_termination" else "check=pass"))


def port_of(pid: str) -> str | None:
    """The C port of a Fortran catalog id, or the Fortran program of a C
    one (None for OpenACC)."""
    m = re.match(r"(omp\d\d-)(c-)?(.*)$", pid)
    if not m:
        return None
    return m.group(1) + (m.group(3) if m.group(2) else "c-" + m.group(3))


def fuzz_ref(run: str, seed: int, gen_version: str, base=(),
             expected: int | None = None) -> ProgramRef:
    from offload.engine.fuzz import generate
    g = generate(seed, gen_version, tuple(base or ()))
    return ProgramRef("fuzz", f"{run}:{seed}", "f90", 52, "omp", True, (),
                      "construct", g.source,
                      expected=f"checksum={g.expected if expected is None else expected}")


def ompvv_ref(path: str, repo: str = "omp_vv") -> ProgramRef:
    src = ROOT / "corpus" / repo / path
    text = src.read_text(errors="replace") if src.is_file() else ""
    return ProgramRef("ompvv", path, lang_of_path(path), 0, "omp", True, (),
                      "exit_code", text, expected="exit=0")


def file_ref(paths: list[str], expected: str = "", label: str = "",
             version: int = 52) -> ProgramRef:
    """A program from files on the command line (one file, or a set in
    compile order); header lines of offload.engine.harness.program_from_file
    (``! legal:``, ``! needs:``) are read from the first file."""
    files = [(Path(p).name, Path(p).read_text()) for p in paths]
    text = join_files(files)
    lang = lang_of_path(paths[0])
    from offload.engine.harness import program_from_file
    prog = program_from_file(paths[0])
    m = re.search(r"^(?:!|//) expected(?: output)?: (.+)$", files[0][1], re.M)
    # The build flags a reproducer needs ("// build flags: -O2
    # -flto"), added by the runners to every build of it
    fl = re.search(r"^(?:!|//)\s*(?:- )?build flags: *(.+?)\s*$",
                   files[0][1], re.M)
    model = prog.model
    # A file of OpenACC directives only is an OpenACC program
    # (its id need not start with accNN-)
    kinds = {g.lower() for d in _DIRECTIVE.finditer(text)
             for g in d.groups()[:2] if g}
    if kinds == {"acc"}:
        model = "acc"
    return ProgramRef("file", label or str(paths[0]), lang, version,
                      model, prog.legal, tuple(prog.needs),
                      prog.evidence, text,
                      expected=expected or (m.group(1).strip() if m else ""),
                      flags=fl.group(1).strip("`") if fl else "")


_DIRECTIVE = re.compile(r"^\s*(?:!\$(omp|acc)|#\s*pragma\s+(omp|acc))\s+(.*)$",
                        re.I | re.M)
_CLAUSE = re.compile(r"\b([a-z_]+)\s*(?=\(|\s|$)", re.I)
_DIRECTIVE_WORDS = {
    "target", "teams", "distribute", "parallel", "do", "for", "simd", "loop",
    "data", "enter", "exit", "update", "declare", "task", "taskloop",
    "taskgroup", "taskwait", "single", "masked", "master", "critical",
    "atomic", "barrier", "ordered", "sections", "section", "workshare",
    "scan", "requires", "mapper", "reduction", "kernels", "serial", "host_data",
    "routine", "wait", "init", "shutdown", "set", "cache", "end", "metadirective",
    "interop", "dispatch", "allocate", "allocators", "error", "nothing", "tile",
    "unroll", "depobj", "flush", "cancel", "workdistribute", "scope",
    "teams", "assume", "assumes"}


_F_CONT = re.compile(r"^(\s*!\$(?:omp|acc)\b.*?)&\s*(?:!.*)?$", re.I)
_F_NEXT = re.compile(r"^\s*!\$(?:omp|acc)\s*&?", re.I)


def join_continuations(text: str) -> str:
    """Directive lines with their continuations joined: Fortran's ``&``
    at the end of a ``!$omp`` / ``!$acc`` line and the next line's
    sentinel (``!$omp&`` or ``!$omp``), C's ``\\`` at the end of a pragma
    line (item 10)."""
    lines = text.split("\n")
    out = []
    k = 0
    while k < len(lines):
        ln = lines[k]
        m = _F_CONT.match(ln)
        while m and k + 1 < len(lines) and _F_NEXT.match(lines[k + 1]):
            k += 1
            ln = m.group(1).rstrip() + " " + _F_NEXT.sub("", lines[k], 1
                                                         ).strip()
            m = _F_CONT.match(ln)
        if re.match(r"^\s*#\s*pragma\b", ln):
            while ln.rstrip().endswith("\\") and k + 1 < len(lines):
                k += 1
                ln = ln.rstrip()[:-1].rstrip() + " " + lines[k].strip()
        out.append(ln)
        k += 1
    return "\n".join(out)


def constructs(text: str) -> frozenset[str]:
    """The directive names (``dir:<name>``) and clause names
    (``clause:<name>``) a program uses (end directives skipped): the
    construct set of a failure signature. Continuation lines are joined
    first (``join_continuations``)."""
    out = set()
    for m in _DIRECTIVE.finditer(join_continuations(text)):
        body = m.group(3).split("!")[0].strip().lower()
        if body.startswith("end"):
            continue
        body = re.sub(r"\([^()]*(?:\([^()]*\)[^()]*)*\)", "()", body)
        words = body.replace(",", " ").split()
        name = []
        for w in words:
            bare = w.split("(")[0]
            if bare in _DIRECTIVE_WORDS and not name or (
                    name and bare in _DIRECTIVE_WORDS and "(" not in w
                    and len(name) < 4):
                name.append(bare)
            else:
                break
        if name:
            out.add("dir:" + " ".join(name))
        for w in words[len(name):]:
            bare = w.split("(")[0].strip(":")
            if re.fullmatch(r"[a-z_]+", bare):
                out.add("clause:" + bare)
    return frozenset(out)
