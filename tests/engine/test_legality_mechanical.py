"""The mechanical legality evidence of a finding (offload.engine.legality_mechanical): the rules engine,
the result hazards, a second witness of another compiler family and the source of the expected value,
all computed from the program and the committed rows, with no AI reading."""
from types import SimpleNamespace

from offload.engine import legality_mechanical as LM

PROG = """program p
  use omp_lib, only: omp_is_initial_device
  implicit none
  integer :: a(8), i, hf
  hf = 1
  !$omp target map(tofrom: a, hf)
  hf = merge(1, 0, omp_is_initial_device())
  do i = 1, 8
    a(i) = i
  end do
  !$omp end target
  print '(a,i0,a,a)', 'RESULT ran_on_host=', hf, ' check=', merge('pass', 'fail', sum(a) == 36)
end program p
"""


def cell(tc, state):
    return SimpleNamespace(tc=tc, state=state, target="mi300a", outcome="RUN_OK" if state == "correct" else "RUN_FAIL")


def test_another_family_that_runs_it_correctly_is_the_witness_and_the_expected_value():
    m = LM.evidence(PROG, "f90", "omp", "wrong_answer", [cell("cce21", "fails-like"), cell("afar", "correct")])
    assert m["rules"] == "accept" and m["witness"] == "accept" and m["expected"] == "other-family"
    assert m["hazards"] == []


def test_gcc_is_never_the_legality_witness_but_may_give_the_expected_value():
    m = LM.evidence(PROG, "f90", "omp", "wrong_answer", [cell("cce21", "fails-like"), cell("gcc", "correct")])
    assert m["witness"] == "same-family" and m["expected"] == "other-family"


def test_a_release_of_the_failing_family_is_no_witness():
    m = LM.evidence(PROG, "f90", "omp", "wrong_answer", [cell("cce21", "fails-like"), cell("cce19", "correct")])
    assert m["witness"] == "same-family"
    assert m["expected"] == "self-check"     # the program checks its own result


def test_the_rules_engine_verdict_and_reasons_are_recorded():
    racy = PROG.replace("  do i = 1, 8\n", "  !$omp parallel do\n  do i = 1, 8\n").replace("    a(i) = i\n", "    hf = i\n    a(i) = i\n")
    m = LM.evidence(racy, "f90", "omp", "wrong_answer", [])
    assert m["rules"] == "reject" and m["rules_why"]


def test_a_stored_front_end_accept_of_another_family_is_the_witness():
    rows = [{"finding": "x", "sha256": "s1", "checker": "afar-frontend", "family": "afar", "result": "accept"}]
    cells = [cell("cce21", "fails-like")]
    assert LM.evidence(PROG, "f90", "omp", "wrong_answer", cells, rows=rows, fid="x", sha="s1")["witness"] == "accept"
    # a row for an old source, or of a failing family, is no witness
    assert LM.evidence(PROG, "f90", "omp", "wrong_answer", cells, rows=rows, fid="x", sha="s2")["witness"] == "same-family"
    afar_fails = [cell("afar", "fails-like")]
    assert LM.evidence(PROG, "f90", "omp", "wrong_answer", afar_fails, rows=rows, fid="x", sha="s1")["witness"] == "same-family"
    rej = [{**rows[0], "result": "reject"}]
    assert LM.evidence(PROG, "f90", "omp", "wrong_answer", cells, rows=rej, fid="x", sha="s1")["witness"] == "reject"


def test_the_findings_that_need_a_front_end_run_are_those_without_a_witness_or_a_current_row():
    rows = [{"finding": "a", "sha256": "s", "checker": "afar-frontend", "family": "afar", "result": "accept"}]
    need = LM.needs_frontend({"a": ("s", {"cce"}), "b": ("s", {"cce"}), "c": ("s", {"afar"}), "d": ("t", set())},
                             rows, witnessed={"d"})
    assert need == ["b"]


def test_the_inputs_hash_changes_with_each_input_of_a_verdict():
    rows = [{"finding": "x", "sha256": "s", "checker": "afar-frontend", "result": "accept"}]
    base = ("s", "wrong_answer", [cell("cce21", "fails-like")], rows, "x", "code")
    h = LM.inputs_hash(*base)
    for i, other in enumerate(("t", "ice", [cell("cce21", "correct")], [{**rows[0], "result": "reject"}], "x", "code2")):
        if i == 4:
            continue
        changed = list(base); changed[i] = other
        assert LM.inputs_hash(*changed) != h, i
    assert LM.inputs_hash(*base[:3], rows + [{**rows[0], "finding": "y"}], "x", "code") == h   # another finding's row


OMP60 = """! Generated by compliance.gen (OpenMP 6.0, free-form Fortran).
program p
  implicit none
  integer :: a(8), i
  !$omp target teams loop induction(step(1), i)
  do i = 1, 8
    a(i) = i
  end do
  print *, a(1)
end program p
"""


def test_a_program_the_header_says_is_openmp_6_0_is_read_as_6_0():
    assert LM.spec_version(OMP60) == 60
    assert LM.spec_version(PROG) == 52
    m = LM.evidence(OMP60, "f90", "omp", "rejected", [])
    assert m["rules"] != "unreadable" or "version:" not in " ".join(m["rules_why"]), m["rules_why"]


def test_nvhpc_is_a_witness_even_where_afar_fails_and_ignoring_directives_is_no_accept():
    rows = [{"finding": "x", "sha256": "s", "checker": "nvhpc269_f90", "family": "nvhpc", "result": "accept"}]
    afar_fails = [cell("afar", "fails-like"), cell("cce21", "fails-like")]
    assert LM.evidence(PROG, "f90", "omp", "wrong_answer", afar_fails, rows=rows, fid="x", sha="s")["witness"] == "accept"
    ign = [{**rows[0], "result": "ignored"}]
    assert LM.evidence(PROG, "f90", "omp", "wrong_answer", afar_fails, rows=ign, fid="x", sha="s")["witness"] == "same-family"
    # which findings each checker family still has to see
    want = {"a": ("s", {"afar"}), "b": ("s", {"cce"})}
    assert LM.needs_frontend(want, rows, set(), family="nvhpc") == ["a", "b"]
    assert LM.needs_frontend(want, [{**rows[0], "finding": "a"}], set(), family="nvhpc") == ["b"]
    assert LM.needs_frontend(want, [], set(), family="afar") == ["b"]


def test_an_nvhpc_check_becomes_a_finding_row_and_an_unreachable_machine_gives_none(monkeypatch):
    from offload.engine.confirm import witness as W
    monkeypatch.setattr(W, "names_for", lambda lang, model="omp": ["nvhpc269_f90", "intel_f90"])
    monkeypatch.setattr(W, "checkers", lambda: {"nvhpc269_f90": {"family": "nvhpc"}, "intel_f90": {"family": "intel"}})
    monkeypatch.setattr(W, "check", lambda *a, **k: {"program": "x", "sha256": "s", "checker": "nvhpc269_f90",
                                                     "version": "26.9", "result": "accept", "message": "",
                                                     "date": "d", "command": "c"})
    r = LM.nvhpc_rows("x", "s", PROG, "f90", "omp")
    assert r == [{"finding": "x", "sha256": "s", "checker": "nvhpc269_f90", "family": "nvhpc", "version": "26.9",
                  "result": "accept", "message": "", "date": "d"}]

    def down(*a, **k):
        raise RuntimeError("ssh to wingtip failed")
    monkeypatch.setattr(W, "check", down)
    assert LM.nvhpc_rows("x", "s", PROG, "f90", "omp") is None


def test_the_evidence_names_the_front_ends_that_saw_the_program():
    rows = [{"finding": "x", "sha256": "s", "checker": "nvhpc_c", "family": "nvhpc", "result": "reject"},
            {"finding": "x", "sha256": "old", "checker": "afar-frontend", "family": "afar", "result": "accept"}]
    m = LM.evidence(PROG, "f90", "omp", "rejected", [cell("cce21", "fails-like")], rows=rows, fid="x", sha="s")
    assert m["front_ends"] == {"nvhpc_c": "reject"} and m["witness"] == "reject"


CPROG = PROG   # the language passed decides the lineage; the text does not matter here


def row(checker, family, result, message=""):
    return {"finding": "x", "sha256": "s", "checker": checker, "family": family, "result": result, "message": message}


def test_a_front_end_of_a_failing_compilers_lineage_is_no_witness():
    cce_c_fails = [cell("cce21", "fails-like")]
    afar_ok = [row("afar-frontend", "afar", "accept")]
    # C: AFAR's clang and CCE's C compiler share a front end
    assert LM.evidence(CPROG, "c", "omp", "rejected", cce_c_fails, rows=afar_ok, fid="x", sha="s")["witness"] == "same-family"
    # Fortran: flang and Cray Fortran do not
    assert LM.evidence(PROG, "f90", "omp", "rejected", cce_c_fails, rows=afar_ok, fid="x", sha="s")["witness"] == "accept"
    icx = [row("intel_c", "intel", "accept")]
    assert LM.evidence(CPROG, "c", "omp", "rejected", cce_c_fails, rows=icx, fid="x", sha="s")["witness"] == "same-family"
    nv = [row("nvhpc_c", "nvhpc", "accept")]
    assert LM.evidence(CPROG, "c", "omp", "rejected", cce_c_fails, rows=nv, fid="x", sha="s")["witness"] == "accept"


def test_a_correct_run_of_the_same_front_end_lineage_does_not_witness_a_refusal():
    cells = [cell("afar", "fails-like"), cell("cce21", "correct")]
    assert LM.evidence(CPROG, "c", "omp", "rejected", cells)["witness"] == "same-family"
    assert LM.evidence(CPROG, "c", "omp", "wrong_answer", cells)["witness"] == "accept"   # the back end failed


def test_a_refusal_for_an_unsupported_feature_is_no_evidence():
    rows = [row("nvhpc_f90", "nvhpc", "reject", "NVFORTRAN-F-1196-OpenMP - omp task is not supported in GPU region (t.f90: 7)")]
    m = LM.evidence(PROG, "f90", "omp", "rejected", [cell("cce21", "fails-like")], rows=rows, fid="x", sha="s")
    assert m["front_ends"] == {"nvhpc_f90": "unsupported"} and m["witness"] == "same-family"
    plain = [row("nvhpc_f90", "nvhpc", "reject", "NVFORTRAN-S-0034-Syntax error at or near + (t.f90: 52)")]
    m = LM.evidence(PROG, "f90", "omp", "rejected", [cell("cce21", "fails-like")], rows=plain, fid="x", sha="s")
    assert m["front_ends"] == {"nvhpc_f90": "reject"} and m["witness"] == "reject"


def test_a_checker_of_a_family_not_under_test_is_valid():
    from offload.engine.confirm import witness as W
    ok = {"intel_f90": {"kind": "offload_compiler", "witness_only": True, "family": "intel", "lang": "f90",
                        "command": "/opt/intel/oneapi/compiler/2025.3/bin/ifx -fiopenmp -c", "version": "ifx --version"}}
    assert W.validate(ok) == ok


def test_a_checker_that_crashes_gives_no_verdict():
    crash = [row("intel_f90", "intel", "reject",
                 "t.f90: error #5633: **Internal compiler error: segmentation violation signal raised** Please report")]
    m = LM.evidence(PROG, "f90", "omp", "rejected", [cell("cce21", "fails-like")], rows=crash, fid="x", sha="s")
    assert m["front_ends"] == {"intel_f90": "ice"} and m["witness"] == "same-family"
    # a stored message joins its lines with " | "; a pattern anchored at a line start still sees each line
    joined = [row("intel_f90", "intel", "reject", "t.f90(3): warning: x | t.f90(7): error #5541: A TASK or TASKGROUP "
                  "construct inside of a TARGET or DECLARE TARGET region is not supported on this platform.")]
    assert LM.evidence(PROG, "f90", "omp", "rejected", [], rows=joined, fid="x", sha="s")["front_ends"] == {"intel_f90": "unsupported"}


def test_gcc_gives_the_expected_value_but_is_never_named_a_witness():
    cells = [cell("cce21", "fails-like"), cell("afar", "correct"), cell("gcc", "correct")]
    m = LM.evidence(PROG, "f90", "omp", "wrong_answer", cells)
    assert m["witnesses"] == ["afar"] and m["expected_from"] == ["afar", "gcc"]
